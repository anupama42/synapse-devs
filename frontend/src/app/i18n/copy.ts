export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const table = lang === 'hi' ? hi : en;
  let value = table[key] ?? en[key] ?? key;
  if (params) {
    for (const [name, param] of Object.entries(params)) {
      value = value.replaceAll(`{${name}}`, String(param));
    }
  }
  return value;
}

export function translatePhrase(lang: Lang, text: string): string {
  if (lang !== 'hi' || !text) return text;
  return phrases[text] ?? text;
}

export function projectCopy(
  lang: Lang,
  slug: string,
  field: 'category' | 'shortDescription' | 'description' | 'role' | 'highlight',
  fallback: string,
): string {
  if (lang !== 'hi') return fallback;
  if (field === 'category') return phrases[fallback] ?? fallback;
  return hiProjects[slug]?.[field] || fallback;
}

export function seoKeyForPath(path: string): string {
  if (path === '/local-business') return 'local';
  if (path === '/web-development') return 'web';
  if (path === '/about') return 'about';
  if (path === '/privacy') return 'privacy';
  if (path === '/terms') return 'terms';
  if (path === '/404') return 'notFound';
  return 'home';
}
